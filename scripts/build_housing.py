# -*- coding: utf-8 -*-
"""Build data/housing.json + data/housing-data.js from the Rating and
Valuation Department's official monthly CSVs (public, via data.gov.hk):
  price:  https://www.rvd.gov.hk/datagovhk/1.4M.csv  (Price Indices by Class)
  rent:   https://www.rvd.gov.hk/datagovhk/1.3M.csv  (Rental Indices by Class)
  yields: https://www.rvd.gov.hk/datagovhk/5.1M.csv  (Property Market Yields)
Usage: python3 scripts/build_housing.py /tmp/hl-price.csv /tmp/hl-rent.csv /tmp/hl-yield.csv
Columns are found by header name, so the script keeps working if the RVD
reorders columns. Months in the files are MM-YYYY; the JSON uses YYYY-MM.
The RVD tables are territory-wide by class; there is no by-area breakdown
in them, so the JSON has no byArea (the page never rendered it).
Monthly series are kept to the latest 24 months to stay small.
"""
import csv, json, os, sys

def load(path):
    with open(path, encoding='utf-8-sig') as f:
        rows = [r for r in csv.reader(f) if r and r[0].strip()]
    # row 0 is a title line, row 1 is the header, rest is data
    return rows[1], rows[2:]

def colidx(header, name):
    for i, h in enumerate(header):
        if h.strip() == name:
            return i
    raise ValueError('column not found: ' + name)

def mmyyyy_to_yyyymm(s):
    m, y = s.strip().split('-')
    return y + '-' + m.zfill(2)

def num(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None

PRICE_COLS = {'all': 'All Classes', 'sm': 'Classes A, B & C',
              'lg': 'Classes D & E', 'A': 'Class A', 'B': 'Class B',
              'C': 'Class C', 'D': 'Class D', 'E': 'Class E'}
RENT_COLS = dict(PRICE_COLS)
YIELD_COLS = {'A': 'Domestic Class A', 'B': 'Domestic Class B',
              'C': 'Domestic Class C', 'D': 'Domestic Class D',
              'E': 'Domestic Class E'}

def series(header, rows, mapping, n=24):
    out = {}
    for key, name in mapping.items():
        c = colidx(header, name)
        out[key] = [[mmyyyy_to_yyyymm(r[0]), num(r[c])] for r in rows[-n:]]
    return out

def is_provisional(header, rows, colname):
    # remark column follows the value column; 'P' = provisional
    c = colidx(header, colname)
    if not rows or c + 1 >= len(rows[-1]):
        return True
    return rows[-1][c + 1].strip() == 'P'

def pct(a, b):
    if a is None or b is None or b == 0:
        return None
    return round((a / b - 1) * 100, 2)

def entry(s, prov):
    return {'value': s[-1][1], 'month': s[-1][0], 'provisional': prov,
            'momPct': pct(s[-1][1], s[-2][1]), 'yoyPct': pct(s[-1][1], s[-13][1])}

def main(price_csv, rent_csv, yield_csv, outdir):
    ph, pr = load(price_csv)
    rh, rr = load(rent_csv)
    yh, yr = load(yield_csv)
    price = series(ph, pr, PRICE_COLS)
    rent = series(rh, rr, RENT_COLS)
    yields = series(yh, yr, YIELD_COLS)
    prov = is_provisional(ph, pr, 'All Classes')
    data = {
        'generatedAt': '2026-11-17',
        'asOf': price['all'][-1][0],
        'baseYear': '1999 = 100',
        'sources': {
            'rvd': 'https://www.rvd.gov.hk/en/publications/property_market_statistics.html',
            'datagovhk': 'https://data.gov.hk/en-data/dataset/hk-rvd-tsinfo_rvd-property-market-statistics',
            'cci': 'https://www.am730.com.hk/article/1063700'
        },
        'notes': '楼价/租金指数及租金回报为差饷物业估价署《物业市场统计资料》公布数字，1999年=100；最近数月为暂定数字，之后会修订。CCL 为中原城市领先指数（中原地产研究部）。',
        'nextRvdUpdate': '2026-11-26',
        'priceIndex': {'latest': entry(price['all'], prov),
                       'byClass': {k: entry(price[k], prov) for k in ['A', 'B', 'C', 'D', 'E']},
                       'monthly': price},
        'rentalIndex': {'latest': entry(rent['all'], prov),
                        'byClass': {k: entry(rent[k], prov) for k in ['A', 'B', 'C', 'D', 'E']},
                        'monthly': rent},
        'yields': {'latest': {k: {'value': yields[k][-1][1], 'month': yields[k][-1][0]}
                             for k in ['A', 'B', 'C', 'D', 'E']},
                   'monthly': yields},
        'cci': {'value': 158.61, 'date': '2026-11-13', 'wowPct': -0.31,
                'mass': 159.62, 'smallMedium': 158.36, 'large': 159.91,
                'hkIsland': 156.58, 'kowloon': 156.77, 'ntEast': 177.64, 'ntWest': 144.70,
                'ytdPct': 10.06, 'vsPeak202108': -17.11, 'weeksDown': 5, 'fiveWeekPct': -1.61}
    }
    json.dump(data, open(outdir + '/housing.json', 'w'), ensure_ascii=False, indent=1)
    js = ('/* Housing data: RVD Property Market Statistics (see housing.json). '
          'Generated by scripts/build_housing.py - do not hand-edit. */\n'
          'var HOUSING_DATA = ' + json.dumps(data, ensure_ascii=False) + ';\n')
    open(outdir + '/housing-data.js', 'w').write(js)
    print('wrote housing.json + housing-data.js, asOf', data['asOf'])
    print('price latest:', data['priceIndex']['latest'])
    print('rent latest:', data['rentalIndex']['latest'])
    print('yields latest:', data['yields']['latest'])

if __name__ == '__main__':
    outdir = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data')
    main(sys.argv[1], sys.argv[2], sys.argv[3], os.path.normpath(outdir))
